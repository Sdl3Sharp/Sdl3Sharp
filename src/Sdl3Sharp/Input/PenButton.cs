namespace Sdl3Sharp.Input;

/// <summary>
/// Represents a button on a pen
/// </summary>
public enum PenButton : byte
{
	/// <summary>No pen button</summary>
	None = 0,

	/// <summary>The pen's first button</summary>
	Button1 = 1,

	/// <summary>The pen's second button</summary>
	Button2 = 2,

	/// <summary>The pen's third button</summary>
	Button3 = 3,

	/// <summary>The pen's fourth button</summary>
	Button4 = 4,

	/// <summary>The pen's fifth button</summary>
	Button5 = 5,
}
